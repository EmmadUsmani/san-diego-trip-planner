/**
 * One-off: fetch real OSRM drive metrics for every consecutive-place pair in the seed itinerary
 * (plus home<->Airbnb) and write db/seed-legs.ts. Run: pnpm tsx db/fetch-legs.ts
 */
import { writeFileSync } from "node:fs";
import { computeLegSpecs } from "../shared/schedule";
import { TRIP_DAYS, laDateKey } from "../shared/time";
import type { TripEvent } from "../shared/types";
import { seedEvents, seedPlaces } from "./seed-data";

const byId = new Map(seedPlaces.map((p) => [p.id, p]));
const byDay = new Map<string, TripEvent[]>();
for (const e of seedEvents as TripEvent[]) {
  const d = laDateKey(e.start);
  byDay.set(d, [...(byDay.get(d) ?? []), e]);
}
for (const l of byDay.values()) l.sort((a, b) => a.start.localeCompare(b.start));
const pairs = new Map<string, [string, string]>();
const add = (a: string, b: string) => {
  if (a !== b) pairs.set(`${a}>${b}`, [a, b]);
};
for (const s of computeLegSpecs(byDay, "pl_airbnb", TRIP_DAYS)) add(s.fromPlaceId, s.toPlaceId);
for (const h of ["pl_valencia", "pl_sylmar"]) {
  add(h, "pl_airbnb");
  add("pl_airbnb", h);
}
add("pl_valencia", "pl_sylmar");
add("pl_sylmar", "pl_airbnb");

const rows: unknown[] = [];
for (const [from, to] of pairs.values()) {
  const a = byId.get(from)!;
  const b = byId.get(to)!;
  const url = `https://router.project-osrm.org/route/v1/driving/${a.lng},${a.lat};${b.lng},${b.lat}?overview=false`;
  const json = (await (await fetch(url, { headers: { "User-Agent": "sd-trip-planner-seed/1.0" } })).json()) as {
    code: string;
    routes?: { distance: number; duration: number }[];
  };
  const r = json.routes?.[0];
  if (json.code !== "Ok" || !r) throw new Error(`OSRM failed ${from}>${to}`);
  const row = {
    fromPlaceId: from,
    toPlaceId: to,
    minutes: Math.max(1, Math.round(r.duration / 60)),
    miles: Math.round((r.distance / 1609.344) * 10) / 10,
  };
  console.log(from, to, row.miles, row.minutes);
  rows.push(row);
  await new Promise((res) => setTimeout(res, 1200));
}
writeFileSync(
  new URL("./seed-legs.ts", import.meta.url),
  `// Generated by db/fetch-legs.ts from the public OSRM API. Do not edit.\nexport const seedLegs: { fromPlaceId: string; toPlaceId: string; minutes: number; miles: number }[] = ${JSON.stringify(rows, null, 2)};\n`,
);
