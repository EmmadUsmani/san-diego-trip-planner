import { writeFileSync } from "node:fs";
import { seedPlaces, seedEvents, seedSettings } from "./seed-data";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "1" : "0";
  if (typeof v === "object") return q(JSON.stringify(v));
  return `'${String(v).replace(/'/g, "''")}'`;
};

const lines: string[] = ["-- Generated by db/make-seed.ts. Do not edit.", "DELETE FROM events;", "DELETE FROM travel_legs;", "DELETE FROM places;", "DELETE FROM settings;"];
for (const p of seedPlaces) {
  lines.push(
    `INSERT INTO places (id,name,category,address,lat,lng,neighborhood,tags,links,default_duration_min,hours_text,notes) VALUES (${[
      p.id, p.name, p.category, p.address, p.lat, p.lng, p.neighborhood, p.tags, p.links, p.defaultDurationMin, p.hoursText, p.notes,
    ].map(q).join(",")});`,
  );
}
for (const e of seedEvents) {
  lines.push(
    `INSERT INTO events (id,place_id,title,kind,start,end,skipped,charge_to_pct,notes) VALUES (${[
      e.id, e.placeId, e.title, e.kind, e.start, e.end, e.skipped, e.chargeToPct, e.notes,
    ].map(q).join(",")});`,
  );
}
for (const [k, v] of Object.entries(seedSettings)) {
  lines.push(`INSERT INTO settings (key,value) VALUES (${q(k)},${q(JSON.stringify(v))});`);
}
writeFileSync(new URL("./seed.sql", import.meta.url), lines.join("\n") + "\n");
console.log(`seed.sql: ${seedPlaces.length} places, ${seedEvents.length} events`);
